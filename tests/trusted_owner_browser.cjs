const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const url = process.env.FIXTURE_URL;
  const artifact = process.env.TRUSTED_OWNER_SCREENSHOT || '/home/oscar/.hermes/cache/scratch/wm-trusted-owner-browser.png';
  const browser = await chromium.launch({headless: true});
  const context = await browser.newContext({viewport:{width:390,height:844}});
  // Fixture-only shell client; real Messenger HTML/JS and HTTP auth handlers below.
  await context.addInitScript(() => {
    const noop = () => {};
    window.WizardApp = {ready:noop,update:{hold:()=>({release:noop})},back:{register:noop},on:noop,nav:{},toast:noop};
  });
  const page = await context.newPage();
  const failures = [];
  page.on('pageerror', e => failures.push(e.message));
  assert.equal((await context.request.get(url+'/')).status(), 401, 'outer auth required');
  await context.request.post(url+'/fixture/login');
  await page.goto(url+'/');
  await page.locator('#setup-form').waitFor({state:'visible'});
  await page.locator('#remember-wizard-label').waitFor({state:'visible'});
  assert.equal(await page.locator('#remember-wizard').isChecked(), false, 'remember is explicit opt-in');
  assert.ok((await page.locator('#remember-wizard').boundingBox()).width <= 28, 'checkbox is not a full-width text input');
  await page.screenshot({path:artifact.replace('.png','-enrollment.png'),fullPage:true});
  await page.locator('#passphrase').fill('synthetic-only-vault-passphrase');
  await page.locator('#remember-wizard').check();
  await page.locator('#setup-submit').click();
  await page.locator('#gate').waitFor({state:'hidden'});
  assert.equal(await page.locator('#passphrase').inputValue(), '', 'secret field cleared');
  await page.reload();
  await page.locator('#gate').waitFor({state:'hidden'});
  await page.goto('about:blank');
  await context.request.post(url+'/fixture/restart');
  await page.goto(url+'/');
  await page.locator('#gate').waitFor({state:'hidden'});
  await page.waitForTimeout(500);
  assert.equal((await context.request.get(url+'/api/status')).status(), 200);
  const status = await (await context.request.get(url+'/api/status')).json();
  assert.equal(status.result.state, 'ready', 'remembered unlock restores ready after actual fixture server restart');
  const cookies = await context.cookies();
  await context.clearCookies();
  for (const cookie of cookies.filter(c => c.name==='fixture_owner')) await context.addCookies([cookie]);
  await page.reload();
  await page.locator('#gate').waitFor({state:'hidden'});
  await page.waitForTimeout(500);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({path:artifact,fullPage:true});
  await page.setViewportSize({width:1280,height:900});
  await page.locator('#gate').waitFor({state:'hidden'});
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({path:artifact.replace('.png','-desktop.png'),fullPage:true});
  // Inner owner cookie alone must not bypass outer sign-out.
  const inner = (await context.cookies()).filter(c => c.name==='wizard_messenger_session');
  await context.clearCookies(); await context.addCookies(inner);
  assert.equal((await context.request.get(url+'/api/view/session')).status(), 401);
  assert.equal((await context.request.get(url+'/api/view/session', {headers:{'X-Messenger-Owner-Proof':'forged'}})).status(), 401);
  assert.deepEqual(failures, []);
  await browser.close();
  console.log('PASS actual served UI: explicit remember, secret clearing, reload, server restart, missing app cookie recovery, outer logout denial; screenshot='+artifact);
})().catch(e=>{console.error(e);process.exit(1)});
